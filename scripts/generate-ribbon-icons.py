"""Generate native geometry from the pinned, selected Fluent SVGs (no external checkout required)."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/fluentui-system-icons"
OUTPUT = ROOT / "QuickExcel.Desktop.Avalonia/Views/RibbonIconData.g.cs"


def generate():
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    paths = []
    for icon in manifest["icons"]:
        raw = (SOURCE / icon["file"]).read_bytes()
        if hashlib.sha256(raw).hexdigest() != icon["sha256"]:
            raise ValueError(f"Source hash mismatch: {icon['file']}")
        svg = ET.fromstring(raw)
        if svg.attrib.get("viewBox") != "0 0 20 20" or len(svg) != 1:
            raise ValueError(f"Expected one path in a 20px viewBox: {icon['file']}")
        path = svg[0]
        if path.tag != "{http://www.w3.org/2000/svg}path" or set(path.attrib) - {"d", "fill", "fill-rule", "clip-rule"}:
            raise ValueError(f"Unsupported SVG content: {icon['file']}")
        if path.attrib.get("fill") not in ("#212121", "currentColor"):
            raise ValueError(f"Expected a monochrome fill: {icon['file']}")
        rule = path.attrib.get("fill-rule", "nonzero")
        if rule not in ("nonzero", "evenodd"):
            raise ValueError(f"Unsupported fill rule: {icon['file']}")
        # SVG defaults to nonzero; Avalonia's geometry mini-language defaults to evenodd.
        paths.append((icon["id"], ("F1 " if rule == "nonzero" else "F0 ") + path.attrib["d"]))
    lines = ["// <auto-generated />", "// Generated by scripts/generate-ribbon-icons.py; do not edit.",
             "// Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation (MIT).",
             "// Source revision: " + manifest["revision"], "namespace QuickExcel.Desktop.Avalonia;", "",
             "internal enum RibbonIcon", "{"]
    lines.extend(f"    {name}," for name, _ in paths)
    lines.extend(["}", "", "internal static class RibbonIconData", "{",
                  "    public static string Path(RibbonIcon icon) => icon switch", "    {"])
    lines.extend(f"        RibbonIcon.{name} => {json.dumps(path)}," for name, path in paths)
    lines.extend(["        _ => throw new ArgumentOutOfRangeException(nameof(icon)),", "    };", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Ribbon icon geometry is stale; run scripts/generate-ribbon-icons.py")
        print("PASS: pinned SVG hashes and generated Ribbon geometry")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
